function renderFilters() {
  const fs = ['All', 'Mobile', 'Web'];
  const labels = { All: 'الكل', Mobile: 'موبايل', Web: 'ويب' };
  $('#filters').innerHTML = fs.map((f) =>
    `<button class="filter ${f === filter ? 'active' : ''}" data-filter="${f}">${lang === 'ar' ? labels[f] : f}</button>`
  ).join('');
  document.querySelectorAll('.filter').forEach((b) => {
    b.onclick = () => { filter = b.dataset.filter; renderFilters(); renderProjects(); };
  });
}

function projectLinks(p) {
  const links = [];
  if (p.links?.web) links.push(`<a class="project-action" href="${p.links.web}" target="_blank" rel="noopener">${trans('view.web')} <span>↗</span></a>`);
  if (p.links?.play) links.push(`<a class="project-action" href="${p.links.play}" target="_blank" rel="noopener">${trans('view.play')} <span>↗</span></a>`);
  if (p.links?.appstore) links.push(`<a class="project-action" href="${p.links.appstore}" target="_blank" rel="noopener">${trans('view.appstore')} <span>↗</span></a>`);
  return links.join('');
}

function projectVisual(p) {
  const cat = lang === 'ar' ? p.categoryAr : p.category;
  if (p.image) {
    const iconClass = p.icon ? ' icon' : '';
    return `<div class="project-visual has-image${iconClass}" style="${p.icon ? `--accent:${p.color}` : ''}"><img src="${p.image}" alt="${lang === 'ar' ? p.ar : p.en}" loading="lazy" /><span class="project-category">${cat}</span></div>`;
  }
  return `<div class="project-visual phone-mock" style="--accent:${p.color}"><div class="phone-frame"><span class="project-symbol">${(p.en || '?').slice(0, 1)}</span></div><span class="project-category">${cat}</span></div>`;
}

function renderProjects() {
  const list = filter === 'All'
    ? projects
    : projects.filter((p) => p.type === filter);

  const featured = filter === 'All' ? list.filter((p) => p.featured) : [];
  const rest = filter === 'All' ? list.filter((p) => !p.featured) : list;

  const card = (p, i, featuredClass = '') => {
    const tags = (p.tags || []).slice(0, featuredClass ? 4 : 3).map((t) => `<span class="tag">${t}</span>`).join('');
    const actions = projectLinks(p);
    const desc = lang === 'ar' ? p.arDesc : p.enDesc;
    return `<article class="project reveal ${featuredClass}" style="transition-delay:${(i % 3) * 0.06}s">
      ${projectVisual(p)}
      <div class="project-body">
        <h3>${lang === 'ar' ? p.ar : p.en}</h3>
        <p class="${featuredClass ? '' : 'project-desc-short'}">${desc}</p>
        <div class="project-tags">${tags}</div>
        ${actions ? `<div class="project-actions">${actions}</div>` : ''}
      </div>
    </article>`;
  };

  let html = '';
  if (featured.length) {
    html += `<div class="projects-featured">${featured.map((p, i) => card(p, i, 'featured')).join('')}</div>`;
  }
  if (rest.length) {
    html += `<div class="projects-rest">${rest.map((p, i) => card(p, i)).join('')}</div>`;
  }
  $('#projects-grid').innerHTML = html;
  observeReveals();
}

function applyLanguage() {
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  document.title = lang === 'ar'
    ? 'business2code | نصنع منتجات رقمية تحرّك الأعمال'
    : 'business2code | Digital products, built to move';
  document.querySelectorAll('[data-t]').forEach((el) => { el.innerHTML = trans(el.dataset.t); });
  document.querySelectorAll('[data-ph]').forEach((el) => { el.placeholder = trans(el.dataset.ph); });
  $('#language').textContent = lang === 'ar' ? 'EN' : 'ع';
  renderServices();
  renderWhy();
  renderIndustries();
  renderFaq();
  renderSteps();
  renderFilters();
  renderProjects();
  observeReveals();
}

function observeReveals() {
  const io = new IntersectionObserver((entries) => {
    entries.forEach((e) => { if (e.isIntersecting) e.target.classList.add('visible'); });
  }, { threshold: 0.08 });
  document.querySelectorAll('.reveal:not(.visible)').forEach((e) => io.observe(e));
}

