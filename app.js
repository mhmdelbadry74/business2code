let lang = 'ar', filter = 'All';
const $ = (s) => document.querySelector(s);
const trans = (k) => translations[lang][k] || k;

function renderServices() {
  $('#services-grid').innerHTML = services.map((s) =>
    `<article class="service reveal"><div class="service-icon">${s[0]}</div><div><h3>${lang === 'ar' ? s[2] : s[1]}</h3><p>${lang === 'ar' ? s[4] : s[3]}</p></div></article>`
  ).join('');
}

function renderFaq() {
  const el = $('#faq-list');
  if (!el) return;
  el.innerHTML = faqs.map((f, idx) =>
    `<details class="faq-item reveal" ${idx === 0 ? 'open' : ''}>
      <summary>${lang === 'ar' ? f[1] : f[0]}</summary>
      <p>${lang === 'ar' ? f[3] : f[2]}</p>
    </details>`
  ).join('');
}

function renderSteps() {
  $('#process-steps').innerHTML = steps.map((s) =>
    `<article class="step reveal"><strong>${s[0]}</strong><div><h3>${lang === 'ar' ? s[2] : s[1]}</h3><p>${lang === 'ar' ? s[4] : s[3]}</p></div></article>`
  ).join('');
}

function renderFilters() {
  const fs = ['All', 'Mobile', 'Web', 'EdTech', 'HealthTech', 'E-commerce'];
  const labels = { All: 'الكل', Mobile: 'موبايل', Web: 'ويب', EdTech: 'EdTech', HealthTech: 'HealthTech', 'E-commerce': 'E-commerce' };
  $('#filters').innerHTML = fs.map((f) =>
    `<button class="filter ${f === filter ? 'active' : ''}" data-filter="${f}">${lang === 'ar' ? labels[f] : f}</button>`
  ).join('');
  document.querySelectorAll('.filter').forEach((b) => {
    b.onclick = () => { filter = b.dataset.filter; renderFilters(); renderProjects(); };
  });
}

function projectLinks(p) {
  const links = [];
  if (p.links?.web) links.push(`<a class="project-action" href="${p.links.web}" target="_blank" rel="noopener">${trans('view.web')} <span>↗</span></a>`);
  if (p.links?.play) links.push(`<a class="project-action" href="${p.links.play}" target="_blank" rel="noopener">${trans('view.play')} <span>↗</span></a>`);
  if (p.links?.appstore) links.push(`<a class="project-action" href="${p.links.appstore}" target="_blank" rel="noopener">${trans('view.appstore')} <span>↗</span></a>`);
  return links.join('');
}

function projectVisual(p) {
  const cat = lang === 'ar' ? p.categoryAr : p.category;
  if (p.image) {
    return `<div class="project-visual has-image"><img src="${p.image}" alt="${lang === 'ar' ? p.ar : p.en}" loading="lazy" /><span class="project-category">${cat}</span></div>`;
  }
  return `<div class="project-visual phone-mock" style="--accent:${p.color}"><div class="phone-frame"><span class="project-symbol">${(p.en || '?').slice(0, 1)}</span></div><span class="project-category">${cat}</span></div>`;
}

